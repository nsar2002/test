    std::vector<int> ParsePattern(const char* pattern)
    {
        std::vector<int> bytes;
        std::istringstream stream(pattern);
        std::string token;
        while (stream >> token)
        {
            if (token == "?" || token == "??")
            {
                bytes.push_back(-1);
            }
            else
            {
                bytes.push_back(static_cast<int>(std::strtoul(token.c_str(), nullptr, 16)));
            }
        }
        return bytes;
    }
































































































































